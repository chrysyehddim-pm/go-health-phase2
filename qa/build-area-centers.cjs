// Offline administrative representative points; never run on member page views.
// Source: taiwan-atlas (MIT), based on Ministry of the Interior town boundaries.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const repo = path.resolve(__dirname, '..');
async function main() {
  const url = 'https://cdn.jsdelivr.net/npm/taiwan-atlas/towns-10t.json';
  const response = await fetch(url);
  if (!response.ok) throw new Error('Boundary download failed: ' + response.status);
  const raw = await response.text(), topology = JSON.parse(raw);
  const arcCache = new Map();
  function arc(index) {
    const original = index < 0 ? ~index : index;
    if (!arcCache.has(original)) {
      let x = 0, y = 0;
      arcCache.set(original, topology.arcs[original].map(p => {
        x += p[0]; y += p[1];
        return [x * topology.transform.scale[0] + topology.transform.translate[0], y * topology.transform.scale[1] + topology.transform.translate[1]];
      }));
    }
    const points = arcCache.get(original);
    return index < 0 ? points.slice().reverse() : points;
  }
  function ring(indices) {
    return indices.flatMap((id, i) => i ? arc(id).slice(1) : arc(id));
  }
  function area(points) {
    return Math.abs(points.reduce((s, p, i) => {const q = points[(i + 1) % points.length]; return s + p[0] * q[1] - q[0] * p[1];}, 0));
  }
  function insidePoint(points) {
    // Widest interior horizontal interval of the largest land polygon. Avoids
    // placing island town centers in the sea or concave-polygon centroids outside.
    const ys = points.map(p => p[1]);
    const y = (Math.min(...ys) + Math.max(...ys)) / 2, xs = [];
    for (let i = 0; i < points.length; i++) {
      const a = points[i], b = points[(i + 1) % points.length];
      if ((a[1] > y) !== (b[1] > y)) xs.push(a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1]));
    }
    xs.sort((a,b) => a-b);
    let pair;
    for (let i=0; i+1<xs.length; i+=2) if (!pair || xs[i+1]-xs[i]>pair[1]-pair[0]) pair=[xs[i],xs[i+1]];
    if (!pair) throw new Error('No interior point');
    return [Number(y.toFixed(6)), Number(((pair[0]+pair[1])/2).toFixed(6))];
  }
  const result = {};
  for (const geom of topology.objects.towns.geometries) {
    const polygons = geom.type === 'Polygon' ? [geom.arcs] : geom.arcs;
    const rings = polygons.map(p => ring(p[0])).sort((a,b) => area(b)-area(a));
    const p = geom.properties;
    const key = (p.COUNTYNAME+p.TOWNNAME).replaceAll('台','臺');
    result[key] = {code:p.TOWNCODE, center:insidePoint(rings[0])};
  }
  // Product-selected, human-readable urban anchors, independent of Google data.
  result['臺北市大安區'].center = [25.0264,121.5435];
  result['新北市板橋區'].center = [25.0119,121.4594];
  const context={window:{}}; vm.runInNewContext(fs.readFileSync(path.join(repo,'assets/tw-districts.js'),'utf8'), context);
  const missing=context.window.GH_TW_AREAS.flatMap(c=>c.districts.filter(d=>!result[(c.name+d.name).replaceAll('台','臺')]).map(d=>c.name+d.name));
  if (missing.length) throw new Error('Missing areas: '+missing.join(','));
  const sha = crypto.createHash('sha256').update(raw).digest('hex');
  const output = '// Generated by qa/build-area-centers.cjs. Representative points, not member locations.\n// Source: '+url+'\n// Source SHA256: '+sha+'\nwindow.GH_AREA_CENTERS = '+JSON.stringify(result,null,2)+';\n'+ "// Replace prototype sequence numbers with official source administrative codes.\nwindow.GH_TW_AREAS?.forEach(county => {\n  county.districts.forEach(district => {\n    const entry = window.GH_AREA_CENTERS[(county.name + district.name).replaceAll('台', '臺')];\n    if (entry) { district.code = entry.code; county.code = entry.code.slice(0, 5); }\n  });\n});\n";
  fs.writeFileSync(path.join(repo,'assets/tw-area-centers.js'),output);
  console.log('Verified representative points for all '+context.window.GH_TW_AREAS.reduce((n,c)=>n+c.districts.length,0)+' districts; source records: '+Object.keys(result).length);
}
main().catch(e=>{console.error(e);process.exitCode=1;});
